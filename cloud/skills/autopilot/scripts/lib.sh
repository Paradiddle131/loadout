#!/usr/bin/env bash
# Shared by the autopilot scripts; the autopilot skill's SKILL.md is the spec.
# Run them from the target repo's root. REST through `gh api` only: GraphQL is refused in cloud sessions.
# The profile sets AUTOPILOT_TRAIN (train delivery) and, when not `main`, AUTOPILOT_BASE.
# DRY_RUN=1 (or --dry-run) runs every read and prints every write as the `gh api` or `git` call
# it would make, so a wake can check the sequence before it mutates anything.
set -euo pipefail

# owner/name of the target, from `origin` unless set (https, ssh or the cloud proxy's URL form).
origin_repo() {
  git remote get-url origin 2>/dev/null | sed -E 's#/+$##; s#\.git$##; s#^.*[:/]([^/:]+/[^/]+)$#\1#'
}
REPO="${AUTOPILOT_REPO:-$(origin_repo || true)}"
# shellcheck disable=SC2034  # used by the sourcing scripts
BASE="${AUTOPILOT_BASE:-main}"
TRAIN="${AUTOPILOT_TRAIN:-claude/autopilot-train}"
# shellcheck disable=SC2034  # used by the sourcing scripts
TRAIN_PR_TITLE="Autopilot train"
# shellcheck disable=SC2034
FOOTER=$'\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_'
DRY_RUN="${DRY_RUN:-0}"
# Run from the skill's own clone by mistake, the scripts would write to the collection's repo.
if [ -z "${AUTOPILOT_REPO:-}" ] && [ -f "$(git rev-parse --show-toplevel 2>/dev/null)/cloud/skills/autopilot/SKILL.md" ]; then
  echo "error: run from the target repo's root, not the skill's own repo (or set AUTOPILOT_REPO)" >&2; exit 1
fi
[ -n "$REPO" ] || { echo "error: no origin remote; set AUTOPILOT_REPO=owner/name" >&2; exit 1; }

now() { date -u +%FT%H:%MZ; }

new_wake_id() { head -c4 /dev/urandom | od -An -tx1 | tr -d ' \n'; }

die() { echo "error: $*" >&2; exit 1; }

# A read: always runs.
gh_get() { gh api "$@"; }

# A write: prints under DRY_RUN, else runs; prints the response on stdout.
gh_write() {
  if [ "$DRY_RUN" = 1 ]; then
    { printf 'dry-run: gh api'; printf ' %q' "$@"; printf '\n'; } >&2
    echo '{}'
  else
    gh api "$@"
  fi
}

# A git command that changes the repo or the remote: printed under DRY_RUN, else run.
git_write() {
  if [ "$DRY_RUN" = 1 ]; then
    { printf 'dry-run: git'; printf ' %q' "$@"; printf '\n'; } >&2
  else
    git "$@" 1>&2   # git chatter stays off stdout, which carries the case name
  fi
}

# A whole `--dry-run` argument sets DRY_RUN=1, never one inside a value such as a note that names
# the flag (call it directly, not in a subshell).
set_dry_run() { for arg in "$@"; do [ "$arg" = --dry-run ] && DRY_RUN=1; done; return 0; }

# The arguments without `--dry-run`, NUL-terminated so a multi-line value stays whole:
# read them back with `mapfile -d '' -t ARGS < <(strip_dry_run "$@")`.
strip_dry_run() {
  for arg in "$@"; do [ "$arg" = --dry-run ] || printf '%s\0' "$arg"; done
}

# The newest PR whose head is the train, as JSON (`null` when none exists).
train_pr() {
  gh_get "repos/$REPO/pulls?head=${REPO%%/*}:$TRAIN&state=all&sort=created&direction=desc&per_page=1" \
    --jq '.[0] // null'
}

# The open train PR's number, or nothing.
open_train_pr_number() {
  gh_get "repos/$REPO/pulls?head=${REPO%%/*}:$TRAIN&state=open&per_page=1" --jq '.[0].number // empty'
}

# Seconds since an ISO timestamp (`YYYY-MM-DDTHH:MMZ` or GitHub's `YYYY-MM-DDTHH:MM:SSZ`).
age_s() { echo $(( $(date -u +%s) - $(date -u -d "$1" +%s) )); }
