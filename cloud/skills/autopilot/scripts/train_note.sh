#!/usr/bin/env bash
# train_note.sh <issue> "<line>" [--sha <commit>] [--gate "<#n title>"] [--dry-run]: the skill's train note (train delivery only).
# Finds the open train PR (opens one when none is open), checks its head contains <commit> when
# given, re-reads the body right before writing, and puts `- Closes #<issue>: <line>` at the end of
# its `## Finished issues`.
# --gate starts the title with `⚑ ` and makes `⚑ Owner gate ready: <#n title>` the body's first line.
# Prints the PR number. Exit 4: the head lacks <commit> (redo step 2, then retry).
# Exit 1 writes nothing: a failed read, or a re-read that is not the PR or has an empty body (a
# 200 with no body is a success to `gh api`), never stands in for the body.
set -euo pipefail
# shellcheck source=lib.sh
. "$(dirname "${BASH_SOURCE[0]}")/lib.sh"

set_dry_run "$@"
mapfile -d '' -t ARGS < <(strip_dry_run "$@")
ISSUE="" LINE="" SHA="" GATE=""
i=0
while [ $i -lt ${#ARGS[@]} ]; do
  case "${ARGS[$i]}" in
    --sha) i=$((i + 1)); SHA="${ARGS[$i]}" ;;
    --gate) i=$((i + 1)); GATE="${ARGS[$i]}" ;;
    *) if [ -z "$ISSUE" ]; then ISSUE="${ARGS[$i]}"; else LINE="${ARGS[$i]}"; fi ;;
  esac
  i=$((i + 1))
done
[[ "$ISSUE" =~ ^[0-9]+$ ]] && [ -n "$LINE" ] || die 'usage: train_note.sh <issue> "<line>" [--sha <commit>] [--gate "<#n title>"] [--dry-run]'

number="$(open_train_pr_number)"   # a failed read stops here: never open a second train PR blind
created=0
if [ -z "$number" ]; then
  title="$TRAIN_PR_TITLE"; body="## Finished issues"   # never empty, so a later empty read is a failure
  [ -n "$GATE" ] && { title="⚑ $title"; body="⚑ Owner gate ready: $GATE"$'\n\n'"$body"; }
  number="$(gh_write -X POST "repos/$REPO/pulls" -f "title=$title" -f "head=$TRAIN" -f "base=$BASE" \
    -f "body=$body" -F draft=false --jq '.number')"
  [ "$DRY_RUN" = 1 ] && number="<new>"
  created=1
fi
[[ "$number" =~ ^[0-9]+$ ]] || [ "$number" = "<new>" ] || die "no train PR number (got '$number')"

if [ -n "$SHA" ] && [ "$DRY_RUN" != 1 ]; then
  git fetch origin "$TRAIN" >/dev/null 2>&1
  git merge-base --is-ancestor "$SHA" "origin/$TRAIN" || { echo "origin/$TRAIN lacks $SHA" >&2; exit 4; }
fi

note="- Closes #$ISSUE: $LINE"
if [ "$DRY_RUN" = 1 ] && [ "$number" = "<new>" ]; then
  echo "dry-run: would append to the new PR: $note" >&2; echo "$number"; exit 0
fi
pr="$(gh_get "repos/$REPO/pulls/$number")"   # re-read right before writing
# The cloud proxy appends an attribution footer to every body `gh` writes; strip it before
# appending, else the footer lands mid-body and stacks.
body="$(jq -r '.body // ""' <<<"$pr" | sed -e :a -e '/^\n*$/{$d;N;ba' -e '}' | sed '/^---$/{N;/\n_Generated by \[Claude Code\]/d}')"
title="$(jq -r '.title' <<<"$pr")"
[ "$(jq -r '.number // empty' <<<"$pr")" = "$number" ] || die "the re-read of PR #$number is not the PR; nothing written"
[ -n "$body" ] || [ "$created" = 1 ] || die "the re-read of PR #$number has an empty body; nothing written"
read_body="$body"
# The line goes after the last Closes line of `## Finished issues` (of the body, in an older body
# without the section); with neither, a new section goes before the first other heading or the
# session footer, so the footer stays last.
[ -n "$body" ] || body="## Finished issues"
body="$(NOTE="$note" awk '
  { line[NR] = $0 }
  END {
    note = ENVIRON["NOTE"]
    for (i = 1; i <= NR; i++) if (line[i] == "## Finished issues") { head = i; break }
    if (head) {
      end = NR
      for (i = head + 1; i <= NR; i++) if (line[i] ~ /^## /) { end = i - 1; break }
      at = head
      for (i = head + 1; i <= end; i++) if (line[i] != "") at = i
      for (i = head + 1; i <= end; i++) if (line[i] ~ /^- Closes #/) last = i
      if (last) at = last
      for (i = 1; i <= NR; i++) { print line[i]; if (i == at) print note }
      exit
    }
    for (i = 1; i <= NR; i++) if (line[i] ~ /^- Closes #/) last = i
    if (last) { for (i = 1; i <= NR; i++) { print line[i]; if (i == last) print note }; exit }
    at = NR + 1
    for (i = 1; i <= NR; i++) if (line[i] ~ /^## / || line[i] ~ /^🤖 Generated with /) { at = i; break }
    for (i = 1; i <= NR + 1; i++) {
      if (i == at) {
        if (i > 1 && line[i - 1] != "") print ""
        print "## Finished issues"; print note
        if (i <= NR) print ""
      }
      if (i <= NR) print line[i]
    }
  }' <<<"$body")"
# The note only adds lines: a body that lost what was read is refused.
[ ${#body} -gt ${#read_body} ] || die "the new body of PR #$number is not longer than the one read; nothing written"
body+=$'\n'
args=(-f "body=$body")
if [ -n "$GATE" ]; then
  [[ "$title" == "⚑ "* ]] || args+=(-f "title=⚑ $title")
  [[ "$body" == "⚑ Owner gate ready:"* ]] || args=(-f "body=⚑ Owner gate ready: $GATE"$'\n\n'"$body" "${args[@]:2}")
fi
gh_write -X PATCH "repos/$REPO/pulls/$number" "${args[@]}" >/dev/null
echo "$number"
