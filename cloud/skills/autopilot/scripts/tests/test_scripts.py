def _patched_body(stderr: str, marker: str = "-X PATCH") -> str:
    """The `body=` value of the dry run's `marker` line, unquoted the way bash's `%q` wrote it."""
    line = next(ln for ln in stderr.splitlines() if marker in ln)
    words = line.removeprefix("dry-run: gh api")
    script = 'eval "set -- $1"; for a; do case $a in body=*) printf %s "${a#body=}";; esac; done'
    unquoted = subprocess.run(  # noqa: S603 (bash unquotes its own %q output)
        [BASH, "-c", script, "_", words], capture_output=True, text=True, check=True
    )
    return unquoted.stdout


@pytest.mark.parametrize(
    ("body", "expected"),
    [
        (
            TRAIN_BODY,
            TRAIN_BODY.replace("not an escape\n", "not an escape\n- Closes #276: placed\n"),
        ),
        (
            "Autopilot train.\n\n## Owner decisions needed\n- none",
            "Autopilot train.\n\n## Finished issues\n- Closes #276: placed\n\n"
            "## Owner decisions needed\n- none",
        ),
        (
            "Autopilot train.\n\n🤖 Generated with [Claude Code](x)",
            "Autopilot train.\n\n## Finished issues\n- Closes #276: placed\n\n"
            "🤖 Generated with [Claude Code](x)",
        ),
        ("", "## Finished issues\n- Closes #276: placed"),
    ],
    ids=["after-the-last-closes", "section-before-the-first-heading", "before-the-footer", "empty"],
)
def test_train_note_places_the_line_in_finished_issues(
    stub: dict[str, str], body: str, expected: str
) -> None:
    fx = Path(stub["STUB_DIR"])
    fx.joinpath("pr_open.json").write_text(json.dumps([{"number": 70}]))
    proxy_footer = "\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_"
    fx.joinpath("pr.json").write_text(
        json.dumps({"number": 70, "title": "Autopilot train", "body": body + proxy_footer})
    )
    done = run("train_note.sh", "276", "placed", "--dry-run", env=stub)
    assert done.returncode == 0, done.stderr
    assert _patched_body(done.stderr) == expected + "\n"


