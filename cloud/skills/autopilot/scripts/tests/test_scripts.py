def test_train_sync_merges_main_into_an_open_train(
    stub: dict[str, str], remote: tuple[Path, Path]
) -> None:
    clone, _ = remote
    _git(clone, "checkout", "-q", "-b", "claude/nightly-roadmap")
    (clone / "b.txt").write_text("b\n")
    _git(clone, "add", "b.txt")
    _git(clone, "commit", "-q", "-m", "train work")
    _git(clone, "push", "-q", "-u", "origin", "claude/nightly-roadmap")
    _git(clone, "checkout", "-q", "main")
    (clone / "c.txt").write_text("c\n")
    _git(clone, "add", "c.txt")
    _git(clone, "commit", "-q", "-m", "main moved")
    _git(clone, "push", "-q", "origin", "main")
    Path(stub["STUB_DIR"], "pr_latest.json").write_text(
        json.dumps([{"number": 9, "state": "open", "merged_at": None, "head": {"sha": "x"}}])
    )
    done = run("train_sync.sh", env=stub, cwd=clone)
    assert done.returncode == 0, done.stderr
    assert done.stdout.strip() == "open-moved"
    assert (clone / "b.txt").exists() and (clone / "c.txt").exists()
    assert (
        _git(clone, "merge-base", "--is-ancestor", "origin/main", "origin/claude/nightly-roadmap")
        == ""
    )


def test_train_sync_rebuilds_a_merged_train_and_cherry_picks_what_landed_after(
    stub: dict[str, str], remote: tuple[Path, Path]
) -> None:
    clone, _ = remote
    _git(clone, "checkout", "-q", "-b", "claude/nightly-roadmap")
    (clone / "b.txt").write_text("b\n")
    _git(clone, "add", "b.txt")
    _git(clone, "commit", "-q", "-m", "merged work")
    merged_head = _git(clone, "rev-parse", "HEAD")
    _git(clone, "checkout", "-q", "main")
    _git(clone, "merge", "-q", "--no-ff", "-m", "Merge train", "claude/nightly-roadmap")
    _git(clone, "push", "-q", "origin", "main")
    _git(clone, "checkout", "-q", "claude/nightly-roadmap")
    (clone / "d.txt").write_text("d\n")
    _git(clone, "add", "d.txt")
    _git(clone, "commit", "-q", "-m", "landed after the merge")
    _git(clone, "push", "-q", "-u", "origin", "claude/nightly-roadmap")
    Path(stub["STUB_DIR"], "pr_latest.json").write_text(
        json.dumps(
            [
                {
                    "number": 9,
                    "state": "closed",
                    "merged_at": "2026-10-25T09:47:37Z",
                    "head": {"sha": merged_head},
                }
            ]
        )
    )
    done = run("train_sync.sh", env=stub, cwd=clone)
    assert done.returncode == 0, done.stderr
    assert done.stdout.strip() == "merged"
    assert (
        _git(clone, "log", "--format=%s", "origin/main..origin/claude/nightly-roadmap")
        == "landed after the merge"
    )
    assert (
        _git(clone, "merge-base", "--is-ancestor", "origin/main", "origin/claude/nightly-roadmap")
        == ""
    )


