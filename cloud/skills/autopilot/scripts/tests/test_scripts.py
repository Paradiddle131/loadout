def _git(cwd: Path, *args: str) -> str:
    return subprocess.run(  # noqa: S603 (fixed git arguments on a temp repo)
        [GIT, *args], cwd=cwd, capture_output=True, text=True, check=True
    ).stdout.strip()


@pytest.fixture
def remote(tmp_path: Path) -> tuple[Path, Path]:
    """A bare `origin` with `main` and a clone of it; (clone, bare)."""
    bare = tmp_path / "origin.git"
    _git(tmp_path, "init", "--bare", "-q", "-b", "main", str(bare))
    clone = tmp_path / "clone"
    _git(tmp_path, "clone", "-q", str(bare), str(clone))
    # A repo-local identity: the scripts' merges and cherry-picks commit too, and a runner may
    # have no ~/.gitconfig.
    for key, value in (("user.name", "t"), ("user.email", "t@x"), ("commit.gpgsign", "false")):
        _git(clone, "config", key, value)
    (clone / "a.txt").write_text("a\n")
    _git(clone, "add", "a.txt")
    _git(clone, "commit", "-q", "-m", "a")
    _git(clone, "push", "-q", "origin", "main")
    return clone, bare


